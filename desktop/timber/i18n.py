"""Tiny translation layer: English / Urdu.

Use ``tr("key")`` everywhere in the UI instead of literal text. The
active language is persisted per-PC via ``app_settings`` and controls
both the words and the layout direction (Urdu = RTL, English = LTR).
"""

from __future__ import annotations

from timber import config
from timber.core import app_settings

LANGUAGES = {"en": "English", "ur": "اردو"}

_current: str | None = None


def get_language() -> str:
    global _current
    if _current is None:
        lang = app_settings.get("language", config.DEFAULT_LANGUAGE)
        _current = lang if lang in LANGUAGES else "en"
    return _current


def set_language(lang: str) -> None:
    global _current
    if lang not in LANGUAGES:
        raise ValueError(f"Unsupported language: {lang!r}")
    _current = lang
    app_settings.set("language", lang)


def layout_direction() -> "Qt.LayoutDirection":  # noqa: F821
    # Imported lazily so the whole business core (which imports i18n for
    # labels) can run WITHOUT the GUI toolkit — that is what lets the future
    # mobile API reuse the exact same accounting logic, and it means the
    # desktop exe never has to be rebuilt to serve the phone app.
    from PySide6.QtCore import Qt

    if get_language() == "ur":
        return Qt.LayoutDirection.RightToLeft
    return Qt.LayoutDirection.LeftToRight


def tr(key: str) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    return entry.get(get_language()) or entry.get("en") or key


