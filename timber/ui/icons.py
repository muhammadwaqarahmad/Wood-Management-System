@lru_cache(maxsize=256)
def _pixmap(name: str, color: str, size: int) -> QPixmap:
    svg = _TMPL.format(c=color, b=_ICONS.get(name, ""))
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    dpr = 2
    pm = QPixmap(size * dpr, size * dpr)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    renderer.render(p)
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


# Nav icons sit on a fixed-width canvas so the view never rescales them;
# the glyph's offset inside the canvas is the tree indentation.
NAV_PAD_MAX = 32


def _padded(pm: QPixmap, pad: int, size: int) -> QPixmap:
    """The glyph drawn at ``pad`` px into a fixed (size+NAV_PAD_MAX)-wide
    transparent canvas — manual indentation without a branch strip."""
    dpr = 2
    raw = QPixmap(pm)
    raw.setDevicePixelRatio(1)  # composite in raw pixels
    out = QPixmap((size + NAV_PAD_MAX) * dpr, size * dpr)
    out.fill(Qt.GlobalColor.transparent)
    p = QPainter(out)
    p.drawPixmap(pad * dpr, 0, raw)
    p.end()
    out.setDevicePixelRatio(dpr)
    return out


def nav_icon(
    name: str, normal: str, selected: str, size: int = 19, pad: int = 0
) -> QIcon:
    """A tintable icon: `normal` colour by default, `selected` when the row
    is. ``pad`` prepends transparent space (manual tree indentation)."""
    icon = QIcon()
    icon.addPixmap(_padded(_pixmap(name, normal, size), pad, size), QIcon.Mode.Normal)
    icon.addPixmap(_padded(_pixmap(name, selected, size), pad, size), QIcon.Mode.Selected)
    icon.addPixmap(_padded(_pixmap(name, selected, size), pad, size), QIcon.Mode.Active)
    return icon


@lru_cache(maxsize=64)
def icon(name: str, color: str, size: int = 18) -> QIcon:
    """A single-colour icon (header buttons, etc.)."""
    return QIcon(_pixmap(name, color, size))


def pixmap(name: str, color: str, size: int = 16) -> QPixmap:
    """A single-colour pixmap (e.g. a chevron on a label)."""
    return _pixmap(name, color, size)
